// Regenerates src/lib/ascii.ts from the Android app's ascii_* string resources,
// so the background art picker offers exactly the same pieces as Android.
// Usage: node scripts/gen-ascii.mjs [path/to/strings.xml]
import { readFileSync, writeFileSync } from "node:fs";

const source = process.argv[2] ?? "../curbox/app/src/main/res/values/strings.xml";
const xml = readFileSync(source, "utf8");

const ENTITIES = { amp: "&", lt: "<", gt: ">", quot: '"', apos: "'" };
const ESCAPES = { n: "\n", t: "\t", "'": "'", '"': '"', "\\": "\\", "@": "@", "?": "?" };

// Android resource rules: quotes keep whitespace and are dropped, unquoted runs
// of whitespace collapse to one space, and backslash escapes apply everywhere.
function decode(raw) {
  const text = raw.replace(/&(#x[0-9a-f]+|#\d+|\w+);/gi, (m, e) =>
    e[0] === "#" ? String.fromCodePoint(e[1].toLowerCase() === "x" ? parseInt(e.slice(2), 16) : Number(e.slice(1))) : (ENTITIES[e] ?? m),
  );
  let out = "";
  let quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (c === "\\") {
      const next = text[++i];
      if (next === "u") {
        out += String.fromCharCode(parseInt(text.slice(i + 1, i + 5), 16));
        i += 4;
      } else out += ESCAPES[next] ?? next ?? "";
    } else if (c === '"') quoted = !quoted;
    else if (!quoted && /\s/.test(c)) {
      if (!out.endsWith(" ")) out += " ";
      while (/\s/.test(text[i + 1] ?? "")) i++;
    } else out += c;
  }
  return out;
}

const arts = [...xml.matchAll(/<string name="ascii_([^"]+)"[^>]*>([\s\S]*?)<\/string>/g)]
  .map(([, name, body]) => [name, decode(body).replace(/^\s*\n/, "").replace(/\s+$/, "")])
  .filter(([, art]) => /[^\s⠀]/.test(art))
  .sort(([a], [b]) => a.localeCompare(b));

const out = `// Generated by scripts/gen-ascii.mjs from the Android ascii_* strings. Do not edit.
// Decorative wallpaper behind the usage header, mirroring AllAppsUsageFragment.

export const ASCII_ART: Record<string, string> = {
${arts.map(([name, art]) => `  ${JSON.stringify(name)}: ${JSON.stringify(art)},`).join("\n")}
};

export const ASCII_NAMES = Object.keys(ASCII_ART);

/** Android shows the chosen piece, or a random one when none is chosen. */
export function asciiFor(name: string): string {
  return ASCII_ART[name] ?? ASCII_ART[ASCII_NAMES[Math.floor(Math.random() * ASCII_NAMES.length)]];
}

/** "praying_angel" -> "Praying angel", like the Android picker. */
export function asciiLabel(name: string): string {
  const words = name.replace(/_/g, " ");
  return words.charAt(0).toUpperCase() + words.slice(1);
}
`;
writeFileSync(new URL("../src/lib/ascii.ts", import.meta.url), out);
console.log(`Wrote ${arts.length} arts: ${arts.map(([n]) => n).join(", ")}`);
